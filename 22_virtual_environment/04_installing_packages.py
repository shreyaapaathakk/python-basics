"""
04_installing_packages.py

Installing packages using pip.
"""

print("Install a package")
print("pip install requests")

print("\nInstall a specific version")
print("pip install requests==2.32.0")

print("\nUpgrade a package")
print("pip install --upgrade requests")

print("\nUninstall a package")
print("pip uninstall requests")

print("\nList installed packages")
print("pip list")
